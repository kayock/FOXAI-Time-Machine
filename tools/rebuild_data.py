#!/usr/bin/env python3
"""
Regenerate js/data.js from content/cards.json and content/worldlines.json.

This is the only "build step" this project has, and it's deliberately tiny:
the JSON files are the human-edited source of truth; this script just
repackages them as a JS file the browser can load directly (browsers won't
fetch() local JSON from a double-clicked file:// page, so we embed it).

Usage:
    python3 tools/rebuild_data.py

No third-party dependencies — standard library only.
"""
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
CARDS_PATH = PROJECT_ROOT / "content" / "cards.json"
WORLDLINES_PATH = PROJECT_ROOT / "content" / "worldlines.json"
INFOGRAPHICS_PATH = PROJECT_ROOT / "content" / "infographics.json"
OUTPUT_PATH = PROJECT_ROOT / "js" / "data.js"


def load_json(path):
    if not path.exists():
        raise SystemExit(f"ERROR: expected content file not found: {path}")
    try:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        raise SystemExit(f"ERROR: {path} is not valid JSON — {e}")


def main():
    cards = load_json(CARDS_PATH)
    worldlines = load_json(WORLDLINES_PATH)
    infographics = load_json(INFOGRAPHICS_PATH) if INFOGRAPHICS_PATH.exists() else []

    if not isinstance(cards, list):
        raise SystemExit(f"ERROR: {CARDS_PATH} must contain a JSON array of cards.")
    if not isinstance(worldlines, list):
        raise SystemExit(f"ERROR: {WORLDLINES_PATH} must contain a JSON array of worldlines.")
    if not isinstance(infographics, list):
        raise SystemExit(f"ERROR: {INFOGRAPHICS_PATH} must contain a JSON array of infographics.")

    # Light sanity check up front — real per-card validation happens in the
    # browser (js/lib.js validateCard), but catching an obviously missing id
    # here saves a confusing round trip.
    missing_id = [i for i, c in enumerate(cards) if not isinstance(c, dict) or not c.get("id")]
    if missing_id:
        print(f"WARNING: {len(missing_id)} card(s) at index {missing_id} have no 'id'. "
              f"They'll still be written, but the app will skip them at runtime.")

    output = []
    output.append("// AUTO-GENERATED by tools/rebuild_data.py — do not edit by hand.")
    output.append("// Edit content/cards.json, content/worldlines.json, and")
    output.append("// content/infographics.json, then re-run:")
    output.append("//   python3 tools/rebuild_data.py")
    output.append("window.TIME_MACHINE_CARDS = " + json.dumps(cards, indent=2, ensure_ascii=False) + ";")
    output.append("")
    output.append("window.TIME_MACHINE_WORLDLINES = " + json.dumps(worldlines, indent=2, ensure_ascii=False) + ";")
    output.append("")
    output.append("window.TIME_MACHINE_INFOGRAPHICS = " + json.dumps(infographics, indent=2, ensure_ascii=False) + ";")
    output.append("")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(output), encoding="utf-8")

    print(f"OK: wrote {OUTPUT_PATH.relative_to(PROJECT_ROOT)} "
          f"({len(cards)} card(s), {len(worldlines)} worldline(s), {len(infographics)} infographic(s)).")


if __name__ == "__main__":
    try:
        main()
    except SystemExit as e:
        print(e, file=sys.stderr)
        sys.exit(1)
